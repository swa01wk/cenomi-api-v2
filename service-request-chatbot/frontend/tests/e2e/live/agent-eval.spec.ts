/**
 * agent-eval.spec.ts — Agent evaluation harness.
 *
 * Drives all 33 eval scenarios (from backend/tests/eval/scenarios.py) against
 * the live backend using real LLM calls, then scores each session using the
 * eval_session.py quality evaluator.
 *
 * Architecture:
 *   1. Each scenario is a Playwright test.
 *   2. The scenario turns are POST'd directly to /api/chat/service-request
 *      (using page.request — no browser UI interaction needed for the turn loop).
 *   3. After the scenario completes, the session ID is used to fetch the
 *      observability replay and score it with eval_session.py (spawned as a
 *      child process).
 *   4. Playwright reports each scenario as PASS/FAIL, with the session eval
 *      score attached as a test annotation.
 *
 * Hard assertions (scenario FAIL):
 *   - Backend returns HTTP error on any turn
 *   - expect_ui_type mismatch
 *   - expect_workflow_stage mismatch
 *   - expect_no_submit violated (ready_to_submit=true when not expected)
 *
 * Soft assertions (annotation only):
 *   - expect_keywords not found in message
 *   - High latency (>15s per turn)
 *   - eval_session quality checks (WARN/FAIL from the session evaluator)
 *
 * Run:
 *   npx playwright test --config playwright.live.config.ts agent-eval.spec.ts
 *   npx playwright test --config playwright.live.config.ts agent-eval.spec.ts --grep "Scenario 1"
 */

import { test, expect, TestInfo } from "@playwright/test";
import { execSync } from "node:child_process";
import * as path from "node:path";
import * as fs from "node:fs";

// ─── Constants ────────────────────────────────────────────────────────────────

const BACKEND_URL = process.env.BACKEND_URL ?? "http://127.0.0.1:8000";
const CHAT_ENDPOINT = `${BACKEND_URL}/api/chat/service-request`;
const HEALTH_ENDPOINT = `${BACKEND_URL}/api/v1/health`;
const EVAL_USER_ID = "playwright-eval-runner";

/** Timeout for a single LLM turn (90s). */
const TURN_TIMEOUT = 90_000;

/** Warn when a turn takes longer than this. */
const SLOW_TURN_MS = 15_000;

// ─── Scenario types (mirrors scenarios.py) ───────────────────────────────────

interface Turn {
  message: string;
  note: string;
  expect_ui_type?: string | null;
  expect_workflow_stage?: string | null;
  expect_keywords?: string[];
  expect_no_submit?: boolean;
  action?: string | null;
  corrected_fields?: Record<string, unknown> | null;
  selected_lease_id?: string | null;
  expect_field_value?: Record<string, string> | null;
}

interface Scenario {
  id: number;
  name: string;
  goal: string;
  turns: Turn[];
  enabled: boolean;
  tags: string[];
}

// ─── Load scenarios from Python JSON export ───────────────────────────────────

/**
 * Export the SCENARIOS list from scenarios.py as JSON by running a tiny Python
 * script in the backend directory.  The result is cached in-process.
 *
 * Fallback: if Python is unavailable (e.g. during CI `--list`), loads from
 * a pre-generated `scenarios.json` file next to this spec (generated by
 * `npm run generate-scenarios`), or returns an empty list so discovery works.
 */
let _scenariosCache: Scenario[] | null = null;

const SCENARIOS_JSON_PATH = path.resolve(__dirname, "scenarios.json");
const BACKEND_DIR = path.resolve(__dirname, "../../../../../backend");

function loadScenarios(): Scenario[] {
  if (_scenariosCache) return _scenariosCache;

  // 1. Try to load via Python (requires venv active)
  try {
    const pythonBin = process.env.PYTHON_BIN ?? "python";
    const scriptPath = path.join(BACKEND_DIR, "_dump_scenarios.py");
    const dumpScript =
      "import json, sys, dataclasses\n" +
      "sys.path.insert(0, '.')\n" +
      "from tests.eval.scenarios import SCENARIOS\n" +
      "print(json.dumps([dataclasses.asdict(s) for s in SCENARIOS]))\n";

    // Write a temp script so we avoid shell-escaping issues with -c
    fs.writeFileSync(scriptPath, dumpScript);
    const raw = execSync(`${pythonBin} "${scriptPath}"`, {
      cwd: BACKEND_DIR,
      timeout: 15_000,
      encoding: "utf-8",
      shell: process.platform === "win32" ? "cmd.exe" : "/bin/bash",
    });
    fs.unlinkSync(scriptPath);
    _scenariosCache = JSON.parse(raw.trim()) as Scenario[];
    return _scenariosCache;
  } catch {
    // Fall through to JSON file fallback
  }

  // 2. Try pre-generated scenarios.json
  if (fs.existsSync(SCENARIOS_JSON_PATH)) {
    try {
      _scenariosCache = JSON.parse(
        fs.readFileSync(SCENARIOS_JSON_PATH, "utf-8"),
      ) as Scenario[];
      return _scenariosCache;
    } catch {
      // Fall through to empty list
    }
  }

  // 3. Empty list — tests will be skipped but discovery won't crash
  // Run `npm run generate-scenarios` to produce scenarios.json
  console.warn(
    "[agent-eval] Could not load scenarios from Python or scenarios.json. " +
    "Run: cd service-request-chatbot/backend && python _dump_scenarios.py > " +
    "../frontend/tests/e2e/live/scenarios.json",
  );
  _scenariosCache = [];
  return _scenariosCache;
}

// ─── HTTP helpers ─────────────────────────────────────────────────────────────

interface TurnPayload {
  user_id: string;
  message: string;
  attachments: unknown[];
  session_id?: string | null;
  action?: string;
  corrected_fields?: Record<string, unknown>;
  selected_lease_id?: string;
}

async function postTurn(
  request: import("@playwright/test").APIRequestContext,
  turn: Turn,
  sessionId: string | null,
): Promise<{ body: Record<string, unknown>; latencyMs: number }> {
  const payload: TurnPayload = {
    user_id: EVAL_USER_ID,
    message: turn.message,
    attachments: [],
  };
  if (sessionId) payload.session_id = sessionId;
  if (turn.action) payload.action = turn.action;
  if (turn.corrected_fields) payload.corrected_fields = turn.corrected_fields;
  if (turn.selected_lease_id) payload.selected_lease_id = turn.selected_lease_id;

  const t0 = Date.now();
  const res = await request.post(CHAT_ENDPOINT, {
    data: payload,
    timeout: TURN_TIMEOUT,
  });
  const latencyMs = Date.now() - t0;

  expect(res.ok(), `HTTP ${res.status()} on turn: "${turn.message}"`).toBeTruthy();
  const body = await res.json() as Record<string, unknown>;
  return { body, latencyMs };
}

// ─── Assertion engine ─────────────────────────────────────────────────────────

interface AssertResult {
  hardFailures: string[];
  softWarnings: string[];
  srReference: string;
  uiType: string;
  workflowStage: string;
}

function assertTurn(turn: Turn, body: Record<string, unknown>): AssertResult {
  const hardFailures: string[] = [];
  const softWarnings: string[] = [];
  let srReference = "";

  const ui = (body.ui ?? {}) as Record<string, unknown>;
  const state = (body.state ?? {}) as Record<string, unknown>;
  const uiType = (ui.type as string) ?? "";
  const workflowStage = (state.workflow_stage as string) ?? "";
  const msg = (body.message as string) ?? "";

  // ── Hard: UI type ──────────────────────────────────────────────────────────
  const CONVERSATIONAL = new Set(["message", "text_question"]);
  if (turn.expect_ui_type != null) {
    const expected = turn.expect_ui_type;
    if (expected === "message") {
      if (!CONVERSATIONAL.has(uiType)) {
        hardFailures.push(
          `ui.type: expected conversational (message/text_question), got '${uiType || "(empty)"}'`,
        );
      }
    } else if (uiType !== expected) {
      hardFailures.push(
        `ui.type: expected '${expected}', got '${uiType || "(empty)"}'`,
      );
    }
  }

  // ── Hard: workflow stage ───────────────────────────────────────────────────
  if (turn.expect_workflow_stage != null) {
    if (workflowStage !== turn.expect_workflow_stage) {
      hardFailures.push(
        `workflow_stage: expected '${turn.expect_workflow_stage}', got '${workflowStage || "(empty)"}'`,
      );
    } else {
      const uuidMatch = msg.match(
        /[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}/i,
      );
      if (uuidMatch) srReference = uuidMatch[0];
    }
  }

  // ── Hard: no-submit guard ──────────────────────────────────────────────────
  if (turn.expect_no_submit && state.ready_to_submit === true) {
    hardFailures.push("ready_to_submit: expected false but got true");
  }

  // ── Soft: keyword check ────────────────────────────────────────────────────
  if (turn.expect_keywords?.length) {
    const msgLower = msg.toLowerCase();
    if (!turn.expect_keywords.some((kw) => msgLower.includes(kw.toLowerCase()))) {
      softWarnings.push(
        `Keywords ${JSON.stringify(turn.expect_keywords)} not found. Got: "${msg.slice(0, 160)}"`,
      );
    }
  }

  // ── Soft: ui.fields value check ───────────────────────────────────────────
  if (turn.expect_field_value) {
    const cardFields = ((ui.fields as Array<Record<string, unknown>>) ?? []);
    for (const [label, expectedVal] of Object.entries(turn.expect_field_value)) {
      const found = cardFields.find(
        (f) => String(f.label ?? "").toLowerCase() === label.toLowerCase(),
      );
      if (!found) {
        softWarnings.push(`ui.fields: field '${label}' not found in confirmation card`);
      } else if (String(found.value ?? "") !== String(expectedVal)) {
        softWarnings.push(
          `ui.fields[${label}]: expected '${expectedVal}', got '${found.value ?? ""}'`,
        );
      }
    }
  }

  return { hardFailures, softWarnings, srReference, uiType, workflowStage };
}

// ─── Session quality evaluator ────────────────────────────────────────────────

interface EvalSummary {
  PASS: number;
  WARN: number;
  FAIL: number;
  INFO: number;
}

interface EvalReport {
  session_id: string;
  trace_count: number;
  summary: EvalSummary;
  turns: Array<{
    turn: number;
    worst_severity: string;
    checks: Array<{ name: string; severity: string; message: string }>;
  }>;
}

/**
 * Run eval_session.py for the given session ID and parse the JSON report.
 * Returns null if the evaluator cannot be reached or the session has no traces.
 */
function runSessionEvaluator(sessionId: string): EvalReport | null {
  const backendDir = path.resolve(__dirname, "../../../../../backend");
  const reportPath = path.join(backendDir, `eval_report_${sessionId}.json`);

  try {
    execSync(
      `python -m tests.eval.eval_session ` +
      `--session-id "${sessionId}" ` +
      `--base-url "${BACKEND_URL}" ` +
      `--output-json "${reportPath}" ` +
      `--no-colour`,
      { cwd: backendDir, timeout: 60_000, stdio: "pipe" },
    );

    if (!fs.existsSync(reportPath)) return null;
    const raw = fs.readFileSync(reportPath, "utf-8");
    fs.unlinkSync(reportPath); // clean up temp file
    return JSON.parse(raw) as EvalReport;
  } catch {
    // Evaluator may fail if observability isn't fully configured — not fatal
    return null;
  }
}

// ─── Test generator ───────────────────────────────────────────────────────────

function describeScenario(scenario: Scenario, testInfo: TestInfo): void {
  testInfo.annotations.push({ type: "goal", description: scenario.goal });
  testInfo.annotations.push({ type: "tags", description: scenario.tags.join(", ") });
}

// ─── Session ID manifest (written at runtime for export_session_observability.py) ──

/** Path where we accumulate session IDs produced during this test run. */
const SESSION_MANIFEST_PATH = path.resolve(
  __dirname,
  "../../../../playwright-report-live/session-ids.json",
);

/** In-memory accumulator; flushed to disk by the @summary test. */
const _collectedSessions: Array<{
  scenario_id: number;
  scenario_name: string;
  session_id: string;
  sr_reference: string;
  passed: boolean;
}> = [];

function appendSessionToManifest(entry: (typeof _collectedSessions)[number]): void {
  _collectedSessions.push(entry);
  try {
    fs.mkdirSync(path.dirname(SESSION_MANIFEST_PATH), { recursive: true });
    // Read existing entries so parallel/sequential test processes don't overwrite each other
    let existing: typeof _collectedSessions = [];
    if (fs.existsSync(SESSION_MANIFEST_PATH)) {
      try { existing = JSON.parse(fs.readFileSync(SESSION_MANIFEST_PATH, "utf-8")); } catch { /* ignore */ }
    }
    // Merge: keep existing entries, replace if same session_id, otherwise append
    const merged = [...existing.filter((e) => e.session_id !== entry.session_id), entry];
    fs.writeFileSync(SESSION_MANIFEST_PATH, JSON.stringify(merged, null, 2));
  } catch {
    // Non-fatal — best effort
  }
}

// ─── Server health check ──────────────────────────────────────────────────────

test.beforeAll(async ({ request }) => {
  const res = await request.get(HEALTH_ENDPOINT, { timeout: 10_000 });
  expect(
    res.ok(),
    `Backend unreachable at ${BACKEND_URL}. Run: uvicorn app.main:app --reload`,
  ).toBeTruthy();
});

// ─── Dynamically generate one test per scenario ───────────────────────────────

const scenarios = loadScenarios().filter((s) => s.enabled);

for (const scenario of scenarios) {
  test(`Scenario ${scenario.id}: ${scenario.name}`, async ({
    request,
  }, testInfo) => {
    describeScenario(scenario, testInfo);

    let sessionId: string | null = null;
    const turnLog: string[] = [];
    let allSoftWarnings: string[] = [];
    let srReference = "";

    for (let i = 0; i < scenario.turns.length; i++) {
      const turn = scenario.turns[i];
      const turnNum = i + 1;

      // POST the turn
      const { body, latencyMs } = await postTurn(request, turn, sessionId);

      // Track session
      sessionId = (body.session_id as string) ?? sessionId;

      // Assert
      const { hardFailures, softWarnings, srReference: ref, uiType, workflowStage } =
        assertTurn(turn, body);

      if (ref) srReference = ref;
      if (softWarnings.length) allSoftWarnings = [...allSoftWarnings, ...softWarnings.map((w) => `T${turnNum}: ${w}`)];

      // Latency warning
      if (latencyMs > SLOW_TURN_MS) {
        allSoftWarnings.push(`T${turnNum}: slow turn ${latencyMs}ms (>${SLOW_TURN_MS}ms)`);
      }

      // Build log entry
      const msg = (body.message as string ?? "").slice(0, 120);
      turnLog.push(
        `T${turnNum} [${hardFailures.length ? "FAIL" : "PASS"}] ` +
        `"${turn.message.slice(0, 60)}" → "${msg}" ` +
        `ui=${uiType} stage=${workflowStage} ${latencyMs}ms`,
      );

      // Hard failures stop the scenario — but first flush session to manifest
      if (hardFailures.length > 0) {
        const failMsg = hardFailures.join("; ");
        testInfo.annotations.push({ type: "failure", description: `Turn ${turnNum}: ${failMsg}` });
        testInfo.annotations.push({ type: "turn_log", description: turnLog.join("\n") });

        // Always write the session ID — partial sessions still have valuable traces
        if (sessionId) {
          appendSessionToManifest({
            scenario_id: scenario.id,
            scenario_name: scenario.name,
            session_id: sessionId,
            sr_reference: srReference,
            passed: false,
          });
          testInfo.annotations.push({ type: "session_id", description: sessionId });
        }

        expect.soft(hardFailures, `Turn ${turnNum} hard failure: ${failMsg}`).toHaveLength(0);
        // Force test failure
        throw new Error(`Scenario ${scenario.id} failed at turn ${turnNum}: ${failMsg}`);
      }
    }

    // ── Attach turn log ────────────────────────────────────────────────────────
    testInfo.annotations.push({ type: "turn_log", description: turnLog.join("\n") });
    if (srReference) {
      testInfo.annotations.push({ type: "sr_reference", description: srReference });
    }

    // ── Write session ID to manifest for export_session_observability.py ──────
    if (sessionId) {
      appendSessionToManifest({
        scenario_id: scenario.id,
        scenario_name: scenario.name,
        session_id: sessionId,
        sr_reference: srReference,
        passed: true,   // reached here = all turns passed (hard failures throw early)
      });
      testInfo.annotations.push({ type: "session_id", description: sessionId });
    }

    // ── Soft warning summary ───────────────────────────────────────────────────
    if (allSoftWarnings.length > 0) {
      testInfo.annotations.push({
        type: "soft_warnings",
        description: allSoftWarnings.join("\n"),
      });
    }

    // ── Run session quality evaluator ──────────────────────────────────────────
    if (sessionId) {
      const evalReport = runSessionEvaluator(sessionId);
      if (evalReport) {
        const { PASS, WARN, FAIL: evalFail, INFO } = evalReport.summary;
        testInfo.annotations.push({
          type: "session_eval",
          description:
            `Session ${sessionId} — ` +
            `${evalReport.trace_count} turns: ` +
            `PASS=${PASS} INFO=${INFO} WARN=${WARN} FAIL=${evalFail}`,
        });

        // Collect eval failures as additional soft warnings (don't fail the test)
        const evalFailChecks = evalReport.turns
          .flatMap((t) =>
            t.checks
              .filter((c) => c.severity === "FAIL")
              .map((c) => `Eval T${t.turn} [${c.name}]: ${c.message}`),
          );
        if (evalFailChecks.length > 0) {
          testInfo.annotations.push({
            type: "eval_failures",
            description: evalFailChecks.join("\n"),
          });
        }
      }
    }
  });
}

// ─── Summary test: consolidate results + auto-export observability data ───────

test("@summary: write combined eval report and export observability", async (
  { request },
  testInfo,
) => {
  const reportDir = path.resolve(
    __dirname,
    "../../../../playwright-report-live",
  );
  const reportPath = path.join(reportDir, "eval-summary.json");

  const health = await request.get(HEALTH_ENDPOINT);
  const sessionIds = _collectedSessions.map((s) => s.session_id);

  const summary = {
    timestamp: new Date().toISOString(),
    backend_url: BACKEND_URL,
    scenario_count: scenarios.length,
    sessions_collected: _collectedSessions.length,
    session_ids: sessionIds,
    sessions: _collectedSessions,
    backend_healthy: health.ok(),
  };

  fs.mkdirSync(reportDir, { recursive: true });
  fs.writeFileSync(reportPath, JSON.stringify(summary, null, 2));

  testInfo.annotations.push({
    type: "report_path",
    description: reportPath,
  });
  testInfo.annotations.push({
    type: "sessions_collected",
    description: `${sessionIds.length} sessions: ${sessionIds.slice(0, 3).join(", ")}${sessionIds.length > 3 ? "..." : ""}`,
  });

  // ── Auto-export observability for all collected sessions ───────────────────
  if (sessionIds.length > 0) {
    const backendDir = path.resolve(__dirname, "../../../../../backend");
    const exportDir = path.join(reportDir, "observability");
    const manifestArg = SESSION_MANIFEST_PATH;

    try {
      const pythonBin = process.env.PYTHON_BIN ?? "python";
      const cmd =
        `${pythonBin} scripts/export_session_observability.py ` +
        `--session-file "${manifestArg}" ` +
        `--base-url "${BACKEND_URL}" ` +
        `--out "${exportDir}" ` +
        `--eval`;

      const output = execSync(cmd, {
        cwd: backendDir,
        timeout: 300_000,  // 5 min for exporting many sessions
        encoding: "utf-8",
        shell: process.platform === "win32" ? "cmd.exe" : "/bin/bash",
      });

      testInfo.annotations.push({
        type: "observability_export",
        description: `Exported to ${exportDir}\n${output.slice(0, 500)}`,
      });

      console.log(`\n✓ Observability data exported to: ${exportDir}`);
      console.log(`  Manifest: ${manifestArg}`);
      console.log(`  Sessions: ${sessionIds.length}`);
    } catch (err) {
      // Non-fatal — export can be run manually
      testInfo.annotations.push({
        type: "export_warning",
        description:
          `Auto-export failed (run manually):\n` +
          `cd service-request-chatbot/backend && ` +
          `python scripts/export_session_observability.py ` +
          `--session-file "${manifestArg}" --out "${exportDir}" --eval\n` +
          String(err).slice(0, 300),
      });
    }
  }

  expect(summary.backend_healthy).toBeTruthy();
});
