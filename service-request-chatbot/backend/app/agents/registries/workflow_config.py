WORKFLOW_CONFIG_REGISTRY: dict[str, WorkflowConfig] = {}


def _build_work_permit_config() -> WorkflowConfig:
    """Build the ``WorkflowConfig`` for the Work Permit Agent.

    Single-stage workflow: the Mall Manager creates a work permit SR.
    There is no FM_REVIEW or RDD_REVIEW phase for work permits.
    """
    from app.agents.prompts.work_permit_extraction_prompt import (
        WORK_PERMIT_EXTRACTION_SYSTEM_PROMPT,
    )

    field_questions: dict[str, str] = {
        "lease_code": "Ask the user for the lease code associated with the unit where work will be performed.",
        "lease_brand_mall": "Ask the user for the lease code, brand name, or mall name to identify the unit.",
        "work_permit_type": (
            "Ask the user what type of work permit they need. "
            "Present the options clearly: "
            "Construction Hot Work, Construction Cold Work, Construction Roof Access, "
            "Maintenance Hot Work, Maintenance Cold Work, Maintenance Roof Access, or Operations."
        ),
        "description": "Ask the user for a brief description of the work to be performed.",
        "start_date": "Ask the user for the start date of the work permit (YYYY-MM-DD).",
        "end_date": "Ask the user for the end date of the work permit (YYYY-MM-DD).",
        "contractor_name": "Ask the user for the name of the contractor performing the work (or say 'none' if not applicable).",
        "comments": "Ask the user if they have any additional comments or instructions for this work permit request.",
    }

    return WorkflowConfig(
        agent_name="work_permit_agent",
        extraction_prompt=WORK_PERMIT_EXTRACTION_SYSTEM_PROMPT,
        field_questions=field_questions,
        stage_sync_nodes={},
        collection_stages=frozenset({"CREATE_WORK_PERMIT"}),
        confirmation_nodes={"CREATE_WORK_PERMIT": "work_permit_confirmation"},
        terminal_stages=frozenset({"WP_CREATED"}),
        backend_fields=frozenset(
            {
                "lease_id",
                "property_id",
                "unit_codes",
                "mall",
                "brand",
                "tenant_profile_id",
                "city",
                "contracted_area",
                "lease",
            }
        ),
        auto_generated_fields=frozenset(),
        lease_trigger_fields=("lease_code", "company", "lease_brand_mall"),
        action_intents=frozenset({"CREATE_WORK_PERMIT_SR"}),
    )


def _fitout_confirm_extraction_prompt() -> str:
    return (
        "You are a field extraction assistant for Fitout Start, Fitout End, and "
        "Trading Confirmation workflows. "
        "Extract only the fields listed below — never invent or guess values.\n\n"

        "## Lease identification\n"
        "lease_code: Short alphanumeric tenant lease identifier — typically 7-10 characters "
        "such as 't0105712', 'T0208831', 'LC-1234'. "
        "It may appear after 'lease', 'for lease', 'unit', or standalone. "
        "Example: 'Confirm fitout for lease t0105712' → lease_code: 't0105712'. "
        "Example: 'Confirm trading for t0105712' → lease_code: 't0105712'.\n"
        "brand: Tenant brand name (e.g. 'Nike', 'Zara').\n"
        "mall: Mall or property name (e.g. 'Riyadh Park').\n"
        "company: Tenant company or legal entity name.\n\n"

        "## Fitout Start fields\n"
        "fitout_start_done: 'yes' or 'no' — whether the fitout has started.\n"
        "actual_fitout_start_date: ISO 8601 date (YYYY-MM-DD) — actual date fitout started.\n"
        "planned_fitout_start_date: ISO 8601 date (YYYY-MM-DD) — revised planned start.\n"
        "planned_fitout_end_date: ISO 8601 date (YYYY-MM-DD) — revised planned end.\n"
        "planned_trading_date: ISO 8601 date (YYYY-MM-DD) — revised planned trading date.\n"
        "delay_reason: Brief text describing the reason for delay.\n\n"

        "## Fitout End fields\n"
        "fitout_complete_done: 'yes' or 'no' — whether the fitout is complete.\n"
        "actual_fitout_complete_date: ISO 8601 date (YYYY-MM-DD) — actual date fitout completed.\n"
        "planned_fitout_complete_date: ISO 8601 date (YYYY-MM-DD) — revised planned completion.\n\n"

        "## Trading fields\n"
        "trading_done: 'yes' or 'no' — whether the unit has started trading.\n"
        "actual_trading_date: ISO 8601 date (YYYY-MM-DD) — actual date trading started.\n\n"

        "## Shared\n"
        "comments: Optional free-form remarks.\n\n"

        "## Critical rules\n"
        "- Convert ALL dates to ISO 8601 (YYYY-MM-DD). Users enter DD/MM/YYYY — convert to YYYY-MM-DD. "
        "e.g. '21/07/2026' → '2026-07-21', '2026-07-21' → '2026-07-21'.\n"
        "- Confirm shortcut: when the assistant's previous question showed a base date "
        "(e.g. 'The base date from the contract is 01/07/2026') and the user replies "
        "'confirm', 'ok', 'yes', 'same', or equivalent agreement, "
        "extract that base date (converted to YYYY-MM-DD) as the value for the actual "
        "date field being asked. "
        "Example: assistant asks about actual_fitout_start_date with base 01/07/2026, "
        "user says 'confirm' → extract actual_fitout_start_date: '2026-07-01'.\n"
        "- Do NOT extract 'inspectionTime', 'startDate', 'endDate', 'description', "
        "or any other handover-specific field — those belong to a different workflow.\n"
        "- Return only fields from the lists above. Never include backend-derived or "
        "system fields like lease_id, property_id, tenant_profile_id.\n"
        "- Output format (JSON object): "
        "{\"summary\": \"one sentence\", \"fields\": {\"<key>\": {\"value\": \"<val>\", \"confidence\": <0.0-1.0>}}}"
    )


