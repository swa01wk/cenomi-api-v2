def _build_rdd_config() -> WorkflowConfig:
    """Build the ``WorkflowConfig`` for the RDD Agent.

    The RDD Agent handles the full RDD lifecycle:
      Phase 1 (CREATE_SR)  — Mall Manager creates the SR
      Phase 2 (FM_REVIEW)  — FM Manager / Operations inspects and adds documents
      Phase 3 (RDD_REVIEW) — DD Engineer reviews, adds documents, approves/rejects

    Deferred to a function so circular imports are avoided — the prompts and
    question maps import from schema modules that may in turn import from the
    registry during collection.
    """
    from app.agents.prompts.handover_extraction_prompt import HANDOVER_EXTRACTION_SYSTEM_PROMPT
    from app.agents.services.missing_field_service import HANDOVER_FIELD_QUESTIONS

    return WorkflowConfig(
        agent_name="rdd_handover_agent",
        extraction_prompt=HANDOVER_EXTRACTION_SYSTEM_PROMPT,
        field_questions=HANDOVER_FIELD_QUESTIONS,
        stage_sync_nodes={
            "FM_REVIEW": "fm_review_entry",
            "RDD_REVIEW": "rdd_review_entry",
        },
        collection_stages=frozenset(
            {"CREATE_SR", "FM_REVIEW", "RDD_REVIEW", "CREATE_HANDED_OVER_SR"}
        ),
        confirmation_nodes={
            "CREATE_SR": "confirmation",
            "FM_REVIEW": "fm_confirmation",
            "RDD_REVIEW": "rdd_confirmation",
            "CREATE_HANDED_OVER_SR": "confirmation",  # reuses same confirmation node
        },
        terminal_stages=frozenset(
            {"SR_CREATED", "SR_COMPLETED", "HANDED_OVER_COMPLETED"}
        ),
        backend_fields=frozenset(
            {
                "tenant_profile_id",
                "property_id",
                "brand_id",
                "lease_id",
                "contract_id",
                "unit_codes",
                "city",
                "contracted_area",
                "lease_brand_mall",
                # 'lease' is a display label set equal to lease_code during lease
                # resolution.  Classifying it as backend-derived ensures it is
                # never surfaced as a user-facing missing-field prompt.
                "lease",
            }
        ),
        # "expected_handover_date" is auto-computed from unit_readiness_date + 7 days
        # "trading_date" is auto-computed from fitout_end_date + 8 days
        # "title" is asked as optional (like description); removed from auto_generated
        # so missing_field_node prompts the user before auto-generating a fallback.
        auto_generated_fields=frozenset({"expected_handover_date", "trading_date"}),
        lease_trigger_fields=("lease_code", "company", "lease_brand_mall"),
        action_intents=frozenset(
            {
                "CREATE_RDD_SERVICE_REQUEST",
                "UPDATE_RDD_SERVICE_REQUEST",
                "APPROVE_RDD_SERVICE_REQUEST",
                "CREATE_HANDED_OVER_SR",
            }
        ),
    )


