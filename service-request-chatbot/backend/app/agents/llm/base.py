"""Base protocol and abstract base class for multi-provider LLM adapters.

Defines the generic ``generate()`` core interface and ``LLMResult`` dataclass,
while ``BaseLLMGateway`` implements ``complete_json()`` as a built-in
convenience wrapper so existing callers work unmodified across all providers.
"""

from __future__ import annotations

import json
from dataclasses import dataclass
from typing import Any, Protocol, runtime_checkable

import structlog

log = structlog.get_logger(__name__)


@dataclass(frozen=True)
class LLMResult:
    """Standardized output returned by provider ``generate()`` calls.

    Attributes
    ----------
    content:
        The raw text response from the assistant.
    parsed:
        Optional parsed JSON dictionary when structured output was requested.
    tool_calls:
        Optional list of tool/function calls requested by the model.
    input_tokens:
        Number of prompt tokens consumed by the call.
    output_tokens:
        Number of completion tokens generated by the call.
    latency_ms:
        Wall-clock latency in milliseconds.
    raw:
        The raw provider-specific SDK response object for advanced debugging.
    """

    content: str
    parsed: dict[str, Any] | None = None
    tool_calls: list[dict[str, Any]] | None = None
    input_tokens: int = 0
    output_tokens: int = 0
    latency_ms: int = 0
    raw: Any = None


@runtime_checkable
class LLMProviderProtocol(Protocol):
    """Protocol satisfied by all concrete LLM provider adapters."""

    @property
    def model(self) -> str:
        """Name of the active chat model."""
        ...

    @property
    def provider_name(self) -> str:
        """Canonical provider name (e.g. 'openai', 'azure_openai', 'vertex_ai')."""
        ...

    async def generate(
        self,
        messages: list[dict[str, Any]],
        *,
        response_format: dict[str, Any] | None = None,
        tools: list[dict[str, Any]] | None = None,
        stream: bool = False,
        temperature: float = 0.0,
        **kwargs: Any,
    ) -> LLMResult:
        """Execute a general LLM chat completion."""
        ...

    async def complete_json(
        self,
        system_prompt: str,
        user_message: str,
    ) -> tuple[dict[str, Any], int, int, int]:
        """Execute JSON completion and return ``(parsed, input_tokens, output_tokens, latency_ms)``."""
        ...


class BaseLLMGateway:
    """Abstract base class implementing the ``complete_json`` convenience wrapper.

    Subclasses must define ``model``, ``provider_name``, and implement
    ``async def generate(...) -> LLMResult``.
    """

    def __init__(self, model: str, provider_name: str) -> None:
        self._model = model
        self._provider_name = provider_name

    @property
    def model(self) -> str:
        return self._model

    @property
    def provider_name(self) -> str:
        return self._provider_name

    async def generate(
        self,
        messages: list[dict[str, Any]],
        *,
        response_format: dict[str, Any] | None = None,
        tools: list[dict[str, Any]] | None = None,
        stream: bool = False,
        temperature: float = 0.0,
        **kwargs: Any,
    ) -> LLMResult:
        raise NotImplementedError("Subclasses must implement generate()")

    async def complete_json(
        self,
        system_prompt: str,
        user_message: str,
    ) -> tuple[dict[str, Any], int, int, int]:
        """Execute JSON completion and return ``(parsed_json, input_tokens, output_tokens, latency_ms)``.

        Acts as a backward-compatible convenience wrapper around ``self.generate()``
        with ``response_format={"type": "json_object"}``.
        """
        result = await self.generate(
            messages=[
                {"role": "system", "content": system_prompt},
                {"role": "user", "content": user_message},
            ],
            response_format={"type": "json_object"},
            temperature=0.0,
        )

        parsed = result.parsed
        if parsed is None:
            raw_content = result.content or "{}"
            parsed = json.loads(raw_content)

        return parsed, result.input_tokens, result.output_tokens, result.latency_ms
